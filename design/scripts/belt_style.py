"""The conveyor belt frame style: src/main/resources/houses/belt.yml (read by `/bakery plot setup`).

Outputs:
  src/main/resources/houses/belt.yml           (the style file the plugin parses)
  design/scripts/previews/belt_preview.png     (the 5-cell factory belt from both sides, pedestal marker)
Run with `mise run assets`. Deterministic. Spec and format: design/conveyor-belt.md

The frame is one column of full blocks per belt cell (nothing beside the belt, so the belt is exactly
the layout cells and nothing collides with props next to the hatch). The moving surface is the
`cookieclicker:conveyor_belt` item display on top of the frame (rubber belt + copper side rails).
`house_factory.py` imports `belt_boxes()` for its camera and hatch previews.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import house_lib  # noqa: E402
from voxel_render import render  # noqa: E402

OUT_YML = ROOT / "src/main/resources/houses/belt.yml"
OUT_PNG = ROOT / "design/scripts/previews/belt_preview.png"

STYLE = {
    "direction": "north",
    "surface-height": 1,
    "item-model": "cookieclicker:conveyor_belt",
    "columns": {
        "roller": ["minecraft:spruce_log[axis=x]"],
        "housing": ["minecraft:waxed_copper_grate[waterlogged=false]"],
    },
    "first": "roller",
    "last": "roller",
    "middle": ["housing", "roller"],
}
AWNING_CLEARANCE = 1 + 13 / 16          # bottom of the copper awning over the hatch (top-half trapdoor at y1)
BELT_THICKNESS = 1 / 16                  # the item model's rubber surface (rails reach 2/16)
COOKIE_HEIGHT = 0.35                     # a belt cookie at the coder's default scale, generous


def validate(style: dict) -> None:
    assert style["direction"] == "north", "the style is drawn for a belt running north (-Z)"
    h = style["surface-height"]
    assert isinstance(h, int) and h >= 1
    assert h + 2 * BELT_THICKNESS + COOKIE_HEIGHT < AWNING_CLEARANCE, "belt + cookies must fit under the awning"
    cols = style["columns"]
    for name, col in cols.items():
        assert len(col) == h, f"column {name}: exactly surface-height blocks (bottom -> top)"
        for data in col:
            house_lib.check_block_data(data)
            block, props = house_lib.parse_block_data(data)
            assert house_lib.is_solid(block), f"{data}: the surface display rests on full blocks"
            assert props.get("axis", "x") in ("x", "y"), "logs lie across the belt (rollers), never along it"
    assert style["first"] in cols and style["last"] in cols and style["middle"]
    assert all(m in cols for m in style["middle"])
    assert style["item-model"] == "cookieclicker:conveyor_belt"


def column_for(style: dict, i: int, n: int) -> list[str]:
    """Frame column (bottom -> top) for belt cell i of n, counted from the hatch (belt_out = 0)."""
    if i == 0:
        return style["columns"][style["first"]]
    if i == n - 1:
        return style["columns"][style["last"]]
    m = style["middle"]
    return style["columns"][m[(i - 1) % len(m)]]


COLOURS = {"spruce_log": (62, 44, 26), "waxed_copper_grate": (176, 102, 76)}


def belt_boxes(style: dict, cells: list[tuple[int, int]], ox: float = 0, oz: float = 0, y0: float = 0):
    """Preview boxes: frame columns + the item-display surface (dark rubber, copper rails), cells (x, z)."""
    s = 1 / 16
    out = []
    n = len(cells)
    h = style["surface-height"]
    for i, (x, z) in enumerate(cells):
        x, z = x + ox, z + oz
        for y, data in enumerate(column_for(style, i, n)):
            block = house_lib.parse_block_data(data)[0]
            if block == "spruce_log":         # bark on top, log ends (rings) on the sides: a roller
                out.append(((x, y0 + y, z + s), (x + 1, y0 + y + 1, z + 1 - s), COLOURS[block]))
                out.append(((x - 0.01, y0 + y + 3 * s, z + 3 * s), (x + 1.01, y0 + y + 13 * s, z + 13 * s),
                            (150, 118, 76)))
            else:
                out.append(((x, y0 + y, z), (x + 1, y0 + y + 1, z + 1), COLOURS[block]))
        top = y0 + h
        out.append(((x + s, top, z), (x + 15 * s, top + s, z + 1), (46, 42, 52)))         # rubber
        out.append(((x, top, z), (x + s, top + 2 * s, z + 1), (192, 107, 79)))            # rails
        out.append(((x + 15 * s, top, z), (x + 1, top + 2 * s, z + 1), (192, 107, 79)))
    return out


def write_yaml(style: dict) -> str:
    q = lambda s: '"' + s + '"'  # noqa: E731
    lst = lambda xs: "[" + ", ".join(q(x) for x in xs) + "]"  # noqa: E731
    cols = style["columns"]
    lines = [
        "# Conveyor belt frame style for /bakery plot setup. GENERATED by design/scripts/belt_style.py; do not edit by hand.",
        "# Spec: design/conveyor-belt.md. The belt cells come from the layout (`layout.belt` in the house file).",
        "#",
        "# Format:",
        "#   direction       the belt runs this way (north = -Z, from the hatch to the pedestal); block states are",
        "#                   written for it. Only north is supported (straight belts, no rotation needed).",
        "#   surface-height  every belt cell gets a frame column of this many blocks, from y 0 (the first air layer",
        "#                   above the ground) upwards. The belt surface rests on top of it: spawn the",
        "#                   `item-model` item display at (cell x + 0.5, ground + surface-height, cell z + 0.5),",
        "#                   transform NONE, scale 1 (the model's bottom is at its origin). Belt cookies ride on",
        "#                   it at ground + surface-height + 0.0625 (the rubber is 1/16 thick).",
        "#   columns         named frame columns, each a list of block data, bottom -> top (length = surface-height).",
        "#   first / last    column name for the first belt cell (belt_out, at the hatch) and the last one (next to",
        "#                   the pedestal).",
        "#   middle          column names repeated over the cells in between, starting with the second cell:",
        "#                   cell i (0 = first) uses middle[(i - 1) % len(middle)].",
        "# Only the belt cells themselves change (no blocks beside the belt), so backup/undo cover exactly",
        "# the belt cells from y 0 to surface-height - 1.",
        f"direction: {style['direction']}",
        f"surface-height: {style['surface-height']}",
        f"item-model: {q(style['item-model'])}",
        "columns:",
    ]
    for name, col in cols.items():
        lines.append(f"  {name}: {lst(col)}")
    lines += [
        f"first: {style['first']}",
        f"last: {style['last']}",
        f"middle: [{', '.join(style['middle'])}]",
    ]
    return "\n".join(lines) + "\n"


def preview(style: dict):
    """The factory belt (5 cells) with a pedestal marker at the north end, from both front sides."""
    cells = [(0, z) for z in range(4, -1, -1)]          # belt_out at z=4, running north to z=0
    boxes = [((-2, -1, -2), (3, 0, 6), (96, 140, 62))]
    boxes += belt_boxes(style, cells, oz=0)
    boxes += [((0.05, 0, -1 + 0.05), (0.95, 0.95, -0.05), (52, 52, 58)),            # pedestal (block display)
              ((0.3, 1.0 + 1 / 16, 1.3), (0.7, 1.15 + 1 / 16, 1.7), (196, 140, 70))]  # a belt cookie
    from PIL import Image
    a = render(boxes, yaw=225, pitch=25, px_per_unit=60)
    b = render(boxes, yaw=135, pitch=25, px_per_unit=60)
    out = Image.new("RGBA", (a.width + b.width + 36, max(a.height, b.height) + 24), (58, 64, 76, 255))
    out.alpha_composite(a, (12, 12))
    out.alpha_composite(b, (a.width + 24, 12))
    return out


def main() -> int:
    validate(STYLE)
    text = write_yaml(STYLE)
    assert yaml.safe_load(text) == STYLE
    OUT_YML.parent.mkdir(parents=True, exist_ok=True)
    OUT_YML.write_text(text, encoding="utf-8")
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    preview(STYLE).save(OUT_PNG)
    print(f"{OUT_YML.relative_to(ROOT)} written; preview {OUT_PNG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
