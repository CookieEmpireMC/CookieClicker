"""The minimal `countryside.yml`: the Mill's box with every cell keep ('.'), same ground-depth, and the Mill placed at [0,0,0].

Output: src/main/resources/houses/countryside.yml. Run with `mise run assets`. Spec: design/countryside.md section 6.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import house_mill as M  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "src/main/resources/houses/countryside.yml"


def main() -> int:
    sx, sy, sz, ground = M.SX, M.SY, M.SZ, M.GROUND
    rows = '"' + "." * sx + '"'
    layer = "  - [" + ", ".join([rows] * sz) + "]"
    out = [
        "# The countryside (countryside-builds): only the Mill for now. GENERATED by design/scripts/countryside.py; do not edit by hand.",
        "# Every cell is keep ('.'); the box is the Mill's box so the Mill pastes at [0, 0, 0].",
        f"size: [{sx}, {sy + ground}, {sz}]",
        "origin: [0, 0, 0]",
        f"ground-depth: {ground}",
        "palette:",
        '  "_": "minecraft:air"',
        "layers:",
    ]
    for y in range(sy + ground):
        out.append(f"  # y={y - ground}")
        out.append(layer)
    out += ["places:", "  mill: {at: [0, 0, 0]}"]
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"houses/countryside.yml: {sx} x {sy + ground} x {sz}, place mill at [0,0,0]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
