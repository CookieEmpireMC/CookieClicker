"""The plot fence style: src/main/resources/houses/fence.yml (read by `/bakery plot fence place`).

Outputs:
  src/main/resources/houses/fence.yml          (the style file the plugin parses)
  design/scripts/previews/fence_preview.png    (textured: the front ring with the gate, seen from outside)
Run with `mise run assets`. Deterministic. Spec and format: design/fence.md

Only non-directional blocks (plus vertical logs), so the coder never has to rotate anything: the same style works on
every side of the ring and around polygon corners. Irregular rhythm (R16): `post-spacing` / `topper-spacing` are
cycled lists, not a fixed number.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import blocks as B  # noqa: E402
import build_lint  # noqa: E402
import design_views  # noqa: E402
import house_lib  # noqa: E402

OUT_YML = ROOT / "src/main/resources/houses/fence.yml"
OUT_PNG = ROOT / "design/scripts/previews/fence_preview.png"

LANTERN = "minecraft:lantern[hanging=false,waterlogged=false]"
CU_LANTERN = "minecraft:waxed_copper_lantern[hanging=false,waterlogged=false]"
STYLE = {
    "rail": "minecraft:dark_oak_fence",
    "post": ["minecraft:stone_bricks", "minecraft:dark_oak_log[axis=y]"],
    "post-spacing": [4, 3, 5, 4, 6, 3, 4, 5],
    "corner": ["minecraft:stone_bricks", "minecraft:mossy_stone_bricks", "minecraft:dark_oak_log[axis=y]"],
    "topper": LANTERN,
    "topper-spacing": [2, 3, 2, 4],
    "gate": {
        "width": 3,
        "left": ["minecraft:stone_bricks", "minecraft:mossy_stone_bricks", "minecraft:stone_bricks",
                 "minecraft:chiseled_stone_bricks", CU_LANTERN],
        "right": ["minecraft:stone_bricks", "minecraft:stone_bricks", "minecraft:mossy_stone_bricks",
                  "minecraft:chiseled_stone_bricks", CU_LANTERN],
        "arch": [None, None, None, "minecraft:dark_oak_planks",
                 "minecraft:dark_oak_slab[type=bottom,waterlogged=false]"],
    },
}


def validate(style: dict) -> None:
    rail_id, props = house_lib.parse_block_data(style["rail"])
    assert not props and house_lib.family(rail_id) == "wood_fence", "rail: a wooden fence id, no states"
    for data in style["post"] + style["corner"] + [style["topper"]] + style["gate"]["left"] + style["gate"]["right"]:
        house_lib.check_block_data(data)
    for data in style["gate"]["arch"]:
        if data is not None:
            house_lib.check_block_data(data)
    for key in ("post", "corner"):
        assert all(house_lib.is_solid(house_lib.parse_block_data(d)[0]) for d in style[key]), f"{key}: rails attach"
    g = style["gate"]
    assert g["width"] == 3 and len(g["left"]) == len(g["right"]) == len(g["arch"])
    clear = next(i for i, d in enumerate(g["arch"]) if d is not None)
    assert clear >= 3, "the opening must stay at least 3 high"
    assert all(d is None for d in g["arch"][:clear]) and all(d is not None for d in g["arch"][clear:])
    assert house_lib.parse_block_data(style["topper"])[0].endswith("lantern")
    for key in ("post-spacing", "topper-spacing"):
        v = style[key]
        assert isinstance(v, list) and 1 <= len(v) <= 32 and all(isinstance(i, int) and 1 <= i <= 64 for i in v), key
    assert "post-every" not in style and "topper-every" not in style, "post-every/topper-every cannot be combined"
    build_lint.lint_fence(style)


def write_yaml(style: dict) -> str:
    q = lambda s: "null" if s is None else '"' + s + '"'  # noqa: E731
    lst = lambda xs: "[" + ", ".join(q(x) for x in xs) + "]"  # noqa: E731
    nums = lambda xs: "[" + ", ".join(str(x) for x in xs) + "]"  # noqa: E731
    g = style["gate"]
    return "\n".join([
        "# Plot fence style for /bakery plot fence place. GENERATED by design/scripts/fence_style.py; do not edit by hand.",
        "# Format and placement rules: design/fence.md. Columns are bottom -> top from the ground surface (y 0 = first",
        "# air block above the ground). Only non-directional blocks, so one style fits every side. Rail connections are computed",
        "# by the plugin; null = air. post-spacing: cycled gaps (blocks) from each side's starting corner; topper-spacing:",
        "# cycled gaps counted in POSTS between lanterns (corners always get one); gate width is centred on the entrance cell.",
        f"rail: {q(style['rail'])}",
        f"post: {lst(style['post'])}",
        f"post-spacing: {nums(style['post-spacing'])}",
        f"corner: {lst(style['corner'])}",
        f"topper: {q(style['topper'])}",
        f"topper-spacing: {nums(style['topper-spacing'])}",
        "gate:",
        f"  width: {g['width']}",
        f"  left: {lst(g['left'])}",
        f"  right: {lst(g['right'])}",
        f"  arch: {lst(g['arch'])}",
    ]) + "\n"


def ring(style: dict, px: int, pz: int, ex: int) -> dict:
    """The fence on the outer ring of a px x pz plot (entrance centre x = ex on the north side) as {(x, y, z): data}
    with connection flags resolved. Mirrors the placement rules in design/fence.md (and the plugin)."""
    cells: dict = {}
    g = style["gate"]

    def column(x, z, col):
        for y, data in enumerate(col):
            if data is not None:
                cells[(x, y, z)] = data

    sides = {                                            # clockwise from each starting corner
        "north": [(x, 0) for x in range(px)],
        "east": [(px - 1, z) for z in range(pz)],
        "south": [(px - 1 - i, pz - 1) for i in range(px)],
        "west": [(0, pz - 1 - i) for i in range(pz)],
    }
    corners = {(0, 0), (px - 1, 0), (px - 1, pz - 1), (0, pz - 1)}
    gate_cells = {(ex + d, 0) for d in (-2, -1, 0, 1, 2)}
    for name, cs in sides.items():
        n = len(cs)
        pos, k = 0, 0
        while True:
            pos += style["post-spacing"][k % len(style["post-spacing"])]
            k += 1
            if pos >= n - 2:
                break
            cells_here = cs[pos]
            near_gate = any(abs(cells_here[0] - gx) <= 1 and cells_here[1] == gy for (gx, gy) in gate_cells)
            if near_gate:
                continue
            cells.setdefault(("post", cells_here), None)
    posts = [(p[1]) for p in cells if isinstance(p[0], str)]
    for key in [p for p in cells if isinstance(p[0], str)]:
        del cells[key]
    # rails everywhere first
    ring_cells = [c for cs in sides.values() for c in cs]
    for (x, z) in ring_cells:
        cells[(x, 0, z)] = B.CONNECT + style["rail"]
    # posts + toppers
    tpos = 0
    for name, cs in sides.items():
        order = [c for c in posts if c in set(cs)]
        order.sort(key=lambda c: cs.index(c))
        t_idx, t_next, t_gap_i = 0, style["topper-spacing"][0], 0
        for i, c in enumerate(order, start=1):
            col = list(style["post"])
            if i == t_next:
                col.append(style["topper"])
                t_gap_i += 1
                t_next += style["topper-spacing"][t_gap_i % len(style["topper-spacing"])]
            for y in range(len(col)):
                cells.pop((c[0], y, c[1]), None)
            column(c[0], c[1], col)
    for c in corners:
        for y in range(4):
            cells.pop((c[0], y, c[1]), None)
        column(c[0], c[1], list(style["corner"]) + [style["topper"]])
    # gate on the north side
    for dx, col in ((-2, g["left"]), (2, g["right"])):
        for y in range(6):
            cells.pop((ex + dx, y, 0), None)
        column(ex + dx, 0, col)
    for dx in (-1, 0, 1):
        for y in range(6):
            cells.pop((ex + dx, y, 0), None)
        column(ex + dx, 0, g["arch"])
    B.resolve(cells)
    return cells


def preview(style: dict) -> None:
    import block_models as bm
    import tex_render as tr
    if not bm.available():
        print("  (client jar not found: textured fence preview skipped)")
        return
    cells = ring(style, 31, 30, 15)
    world = {p: d for p, d in cells.items() if p[2] <= 4 or p[2] >= 25}
    world.update(design_views.ground_world(-6, -8, 36, 6))
    img = design_views.render_world(world, (15.5, 3.0, -9.0), (15.5, 1.5, 0), (1280, 520))
    img.save(OUT_PNG)


def main() -> int:
    validate(STYLE)
    text = write_yaml(STYLE)
    assert yaml.safe_load(text) == STYLE
    OUT_YML.parent.mkdir(parents=True, exist_ok=True)
    OUT_YML.write_text(text, encoding="utf-8")
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    preview(STYLE)
    print(f"{OUT_YML.relative_to(ROOT)} written; preview {OUT_PNG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
