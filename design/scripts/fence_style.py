"""The plot fence style: src/main/resources/houses/fence.yml (read by `/bakery plot fence place`).

Outputs:
  src/main/resources/houses/fence.yml          (the style file the plugin parses)
  design/scripts/previews/fence_preview.png    (the front side of the factory plot ring with the gate)
Run with `mise run assets`. Deterministic. Spec and format: design/fence.md

Only non-directional blocks (plus vertical logs), so the coder never has to rotate anything:
the same style works on every side of the ring and around polygon corners.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import house_lib  # noqa: E402
from voxel_render import render  # noqa: E402

OUT_YML = ROOT / "src/main/resources/houses/fence.yml"
OUT_PNG = ROOT / "design/scripts/previews/fence_preview.png"

STYLE = {
    "rail": "minecraft:spruce_fence",
    "post": ["minecraft:spruce_log[axis=y]"],
    "post-every": 4,
    "corner": ["minecraft:stone_bricks", "minecraft:spruce_log[axis=y]"],
    "topper": "minecraft:lantern[hanging=false,waterlogged=false]",
    "topper-every": 2,
    "gate": {
        "width": 3,
        "left": ["minecraft:stone_bricks", "minecraft:bricks", "minecraft:bricks", "minecraft:chiseled_stone_bricks",
                 "minecraft:waxed_copper_lantern[hanging=false,waterlogged=false]"],
        "right": ["minecraft:stone_bricks", "minecraft:bricks", "minecraft:bricks", "minecraft:chiseled_stone_bricks",
                  "minecraft:waxed_copper_lantern[hanging=false,waterlogged=false]"],
        "arch": [None, None, None, "minecraft:dark_oak_planks",
                 "minecraft:dark_oak_slab[type=bottom,waterlogged=false]"],
    },
}


def validate(style: dict) -> None:
    rail_id, props = house_lib.parse_block_data(style["rail"])
    assert not props and house_lib.family(rail_id) == "wood_fence", "rail: a wooden fence id, no states"
    for data in style["post"] + style["corner"] + [style["topper"]] + style["gate"]["left"] + style["gate"]["right"]:
        house_lib.check_block_data(data)
    for data in style["gate"]["arch"]:
        if data is not None:
            house_lib.check_block_data(data)
    for key in ("post", "corner"):
        assert all(house_lib.is_solid(house_lib.parse_block_data(d)[0]) for d in style[key]), f"{key}: rails attach"
    g = style["gate"]
    assert g["width"] == 3 and len(g["left"]) == len(g["right"]) == len(g["arch"])
    clear = next(i for i, d in enumerate(g["arch"]) if d is not None)
    assert clear >= 3, "the opening must stay at least 3 high"
    assert all(d is None for d in g["arch"][:clear]) and all(d is not None for d in g["arch"][clear:])
    assert house_lib.parse_block_data(style["topper"])[0].endswith("lantern")
    assert style["post-every"] >= 2 and style["topper-every"] >= 1


def write_yaml(style: dict) -> str:
    q = lambda s: "null" if s is None else '"' + s + '"'  # noqa: E731
    lst = lambda xs: "[" + ", ".join(q(x) for x in xs) + "]"  # noqa: E731
    g = style["gate"]
    return "\n".join([
        "# Plot fence style for /bakery plot fence place. GENERATED by design/scripts/fence_style.py; do not edit by hand.",
        "# Format and placement rules: design/fence.md. Columns are bottom -> top from the ground surface (y 0 = first",
        "# air block above the ground). Only non-directional blocks, so one style fits every side. Rail connections are computed",
        "# by the plugin; null = air; topper sits on every 2nd post and all corners; gate width is centred on the entrance cell.",
        f"rail: {q(style['rail'])}",
        f"post: {lst(style['post'])}",
        f"post-every: {style['post-every']}",
        f"corner: {lst(style['corner'])}",
        f"topper: {q(style['topper'])}",
        f"topper-every: {style['topper-every']}",
        "gate:",
        f"  width: {g['width']}",
        f"  left: {lst(g['left'])}",
        f"  right: {lst(g['right'])}",
        f"  arch: {lst(g['arch'])}",
    ]) + "\n"


def preview(style: dict):
    """Front ring of the 31-wide factory plot (entrance at x=15), plus two side cells at each corner."""
    col = {"spruce_fence": (115, 85, 52), "spruce_log": (62, 44, 26), "stone_bricks": (122, 121, 122),
           "bricks": (150, 82, 66), "chiseled_stone_bricks": (118, 117, 118), "lantern": (236, 178, 72),
           "waxed_copper_lantern": (120, 200, 120), "dark_oak_planks": (66, 44, 22), "dark_oak_slab": (78, 52, 28)}
    s = 1 / 16
    boxes = [((-1, -1, -1), (32, 0, 4), (96, 140, 62))]

    def column(x, z, datas):
        for y, data in enumerate(datas):
            if data is None:
                continue
            b = house_lib.parse_block_data(data)[0]
            if b.endswith("lantern"):
                boxes.append(((x + 5 * s, y, z + 5 * s), (x + 11 * s, y + 7 * s, z + 11 * s), col[b]))
            elif b.endswith("_slab"):
                boxes.append(((x, y, z), (x + 1, y + .5, z + 1), col[b]))
            else:
                boxes.append(((x, y, z), (x + 1, y + 1, z + 1), col[b]))

    def rail(x, z, east, west, north=False, south=False):
        c = col["spruce_fence"]
        boxes.append(((x + 6 * s, 0, z + 6 * s), (x + 10 * s, 1, z + 10 * s), c))
        for on, (x1, z1, x2, z2) in ((east, (.5, 7 * s, 1, 9 * s)), (west, (0, 7 * s, .5, 9 * s)),
                                     (north, (7 * s, 0, 9 * s, .5)), (south, (7 * s, .5, 9 * s, 1))):
            if on:
                for y1, y2 in ((6 * s, 9 * s), (12 * s, 15 * s)):
                    boxes.append(((x + x1, y1, z + z1), (x + x2, y2, z + z2), c))

    g = style["gate"]
    ex = 15
    left_x, right_x = ex - 2, ex + 2
    post_no = 0
    for x in range(31):
        if x in (0, 30):
            column(x, 0, style["corner"] + [style["topper"]])
            for z in (1, 2):
                rail(x, z, False, False, north=True, south=z == 1)
        elif x == left_x:
            column(x, 0, g["left"])
        elif x == right_x:
            column(x, 0, g["right"])
        elif abs(x - ex) <= 1:
            column(x, 0, g["arch"])
        elif x % style["post-every"] == 0 and abs(x - ex) > 3:      # no post right beside a gate pillar
            post_no += 1
            top = [style["topper"]] if post_no % style["topper-every"] == 0 else []
            column(x, 0, style["post"] + top)
        else:
            rail(x, 0, True, True)
    return render(boxes, yaw=200, pitch=20, px_per_unit=30)


def main() -> int:
    validate(STYLE)
    text = write_yaml(STYLE)
    assert yaml.safe_load(text) == STYLE
    OUT_YML.parent.mkdir(parents=True, exist_ok=True)
    OUT_YML.write_text(text, encoding="utf-8")
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    preview(STYLE).save(OUT_PNG)
    print(f"{OUT_YML.relative_to(ROOT)} written; preview {OUT_PNG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
