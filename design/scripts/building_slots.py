"""Slots of the visible bakery buildings on the factory plot: src/main/resources/houses/building-slots.yml

Format: slots: { <building id>: [ {at: [x, y, z], yaw: <deg>}, ... ] }
`at` = plot cell from the plot's min corner (same frame as layout: in houses/factory.yml: x west->east,
z north->south, y 0 = first air layer). The model's bottom centre stands at the cell centre (x + 0.5, y, z + 0.5).
`yaw` = Minecraft facing yaw of the building's front (0 south, 90 west, 180 north, 270 east).
Every building fits a centred square (side 2 * footprint half extent, any yaw); the generator asserts that these
squares stay inside the fence, off the factory/front zones, and off each other. Spec: design/buildings-world.md
Also imported by decor_style.py (zone_cells) so no decor sits in or next to a slot.
Deterministic.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import building_world  # noqa: E402

OUT = ROOT / "src/main/resources/houses/building-slots.yml"
PLOT_X, PLOT_Z = 31, 30

# real zones in blocks [x0, z0, x1, z1): factory with margin, front zone (gate walk, pedestal, panels, belt)
ZONES = {"factory": (5, 9, 26, 25), "front": (12, 1, 24, 9)}

# (cell x, cell z, yaw)
SLOT_CELLS = {
    # a little crew queueing beside the walk in the front-west yard, facing east (towards the walk)
    "villager_baker": [(5, 2, 270), (7, 2, 270), (9, 2, 270), (5, 4, 270), (7, 4, 270), (9, 4, 270),
                       (7, 6, 270), (9, 6, 270)],
    # ovens along the east wall, fronts to the west (the factory)
    "industrial_oven": [(27, 12, 90), (27, 15, 90), (27, 18, 90), (27, 21, 90)],
    # two extra belts behind the factory
    "extra_belt": [(10, 26, 180), (14, 26, 180)],
    # the shipping yard and the lab on the west side, fronts to the east
    "shipping_centre": [(2, 12, 270), (2, 15, 270)],
    "alchemy_lab": [(2, 19, 270), (2, 22, 270)],
    # the portal in the north-east corner, facing west across the walk
    "portal_bakery": [(27, 4, 90)],
}
CAPS = {"villager_baker": 8, "industrial_oven": 4, "extra_belt": 2, "shipping_centre": 2, "alchemy_lab": 2, "portal_bakery": 1}


def half(bid: str) -> float:
    return building_world.footprint(bid)


def square(bid: str, x: int, z: int, margin: float = 0.0):
    h = half(bid) + margin
    return (x + 0.5 - h, z + 0.5 - h, x + 0.5 + h, z + 0.5 + h)


def zone_cells(margin: float = 0.0, exact: bool = True) -> set[tuple[int, int]]:
    """Plot cells touched by a slot footprint (expanded by `margin` blocks)."""
    cells = set()
    for bid, lst in SLOT_CELLS.items():
        for x, z, _ in lst:
            x0, z0, x1, z1 = square(bid, x, z, margin)
            for cx in range(math.floor(x0), math.ceil(x1)):
                for cz in range(math.floor(z0), math.ceil(z1)):
                    cells.add((cx, cz))
    return cells


def overlap(a, b, gap=0.0):
    return a[0] < b[2] + gap and b[0] < a[2] + gap and a[1] < b[3] + gap and b[1] < a[3] + gap


def validate():
    all_sq = []
    for bid, lst in SLOT_CELLS.items():
        assert len(lst) == CAPS[bid] <= 10, bid
        for x, z, yaw in lst:
            assert yaw in (0, 90, 180, 270)
            sq = square(bid, x, z)
            assert sq[0] >= 1.2 and sq[1] >= 1.2 and sq[2] <= PLOT_X - 1 - 0.2 and sq[3] <= PLOT_Z - 1 - 0.2, (bid, x, z, sq)
            for name, zn in ZONES.items():
                assert not overlap(sq, zn, 0.1), f"{bid} {(x, z)} hits zone {name}"
            for other in all_sq:
                assert not overlap(sq, other[1], 0.25), f"{bid} {(x, z)} touches {other[0]}"
            all_sq.append((f"{bid}{(x, z)}", sq))


def write():
    lines = ["# Slots of the visible bakery buildings. GENERATED by design/scripts/building_slots.py; do not edit by hand.",
             "# Spec: design/buildings-world.md. at = [x, y, z] plot cells from the plot's min corner (frame of layout: in factory.yml);",
             "# the model's bottom centre stands at the cell centre. yaw = facing of the building's front (0 south, 90 west, 180 north, 270 east).",
             "# Instance i of a building shows on slot i; the slot count is the visual cap.", "slots:"]
    for bid, lst in SLOT_CELLS.items():
        h = half(bid)
        lines.append(f"  # {bid}: footprint square {2 * h:.2f} x {2 * h:.2f} blocks around the cell centre")
        lines.append(f"  {bid}:")
        for x, z, yaw in lst:
            lines.append(f"    - {{at: [{x}, 0, {z}], yaw: {yaw}}}")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    validate()
    write()
    print(f"wrote {OUT}: " + ", ".join(f"{b} x{len(v)} (half {half(b):.2f})" for b, v in SLOT_CELLS.items()))
