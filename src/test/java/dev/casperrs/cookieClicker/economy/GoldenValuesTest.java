package dev.casperrs.cookieClicker.economy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.yaml.snakeyaml.Yaml;

/**
 * Checks the Java economy against {@code docs/balance/golden-values.json} (generated by the simulator
 * from docs/balance/model.md), using the real {@code buildings.yml} / {@code upgrades.yml} from the jar's
 * resources. Skipped while any of those files is missing (before the balance-designer branch is merged).
 */
class GoldenValuesTest {

    private static final Path GOLDEN = Path.of("docs/balance/golden-values.json");

    private static JsonObject golden() throws IOException {
        Assumptions.assumeTrue(Files.isRegularFile(GOLDEN), "docs/balance/golden-values.json not present yet");
        try (Reader r = Files.newBufferedReader(GOLDEN, StandardCharsets.UTF_8)) {
            return JsonParser.parseReader(r).getAsJsonObject();
        }
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> resourceYaml(String name) throws IOException {
        try (InputStream in = GoldenValuesTest.class.getClassLoader().getResourceAsStream(name)) {
            Assumptions.assumeTrue(in != null, name + " not present yet");
            Object o = new Yaml().load(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            return (Map<String, Object>) o;
        }
    }

    private static Economy economy() throws Exception {
        EconomyConfig config = EconomyConfigParser.parse(resourceYaml("buildings.yml"), resourceYaml("upgrades.yml")).config();
        return new Economy(config, new java.util.Random(1));
    }

    private static void assertClose(double expected, double actual, String what) {
        double tolerance = 1e-9 * Math.max(Math.abs(expected), Math.abs(actual));
        assertEquals(expected, actual, tolerance, what);
    }

    @Test
    void costGrowthMatches() throws Exception {
        JsonObject g = golden();
        Economy e = economy();
        assertEquals(g.get("cost-growth").getAsDouble(), e.config().costGrowth());
    }

    @Test
    void singleAndBulkCostsMatchExactly() throws Exception {
        JsonObject costs = golden().getAsJsonObject("costs");
        Economy e = economy();
        assertFalse(costs.isEmpty());
        assertEquals(costs.keySet(), e.config().buildings().keySet(), "building IDs in golden values vs buildings.yml");
        for (String id : costs.keySet()) {
            JsonObject spec = costs.getAsJsonObject(id);
            JsonArray single = spec.getAsJsonArray("single");
            assertEquals(101, single.size());
            for (int n = 0; n < single.size(); n++) {
                // costs are integers stored as numbers; compare exactly
                assertEquals(single.get(n).getAsDouble(), e.bulkCost(id, n, 1), id + " single cost at owned=" + n);
            }
            for (Map.Entry<String, JsonElement> bulk : spec.getAsJsonObject("buy-10-from").entrySet()) {
                int from = Integer.parseInt(bulk.getKey());
                assertEquals(bulk.getValue().getAsDouble(), e.bulkCost(id, from, 10), id + " buy-10 from " + from);
            }
        }
    }

    @Test
    void cpsAndClickPowerMatchForRecordedStates() throws Exception {
        JsonArray states = golden().getAsJsonArray("states");
        Economy e = economy();
        assertTrue(states.size() > 0);
        for (JsonElement el : states) {
            JsonObject s = el.getAsJsonObject();
            Map<String, Integer> owned = new HashMap<>();
            s.getAsJsonObject("owned").entrySet().forEach(en -> owned.put(en.getKey(), en.getValue().getAsInt()));
            Set<String> upgrades = new HashSet<>();
            s.getAsJsonArray("upgrades").forEach(u -> upgrades.add(u.getAsString()));
            CookiePouch p = CookiePouch.fromSnapshot(new PouchSnapshot(0, 0, owned, upgrades));
            String label = s.get("profile").getAsString() + "@" + s.get("time").getAsInt() + "s";
            assertClose(s.get("total-cps").getAsDouble(), e.totalCps(p), "total-cps " + label);
            assertClose(s.get("click-power").getAsDouble(), e.clickPower(p), "click-power " + label);
        }
    }
}
