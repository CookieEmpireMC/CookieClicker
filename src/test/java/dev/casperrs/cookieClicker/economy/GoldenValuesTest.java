package dev.casperrs.cookieClicker.economy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.Map;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.yaml.snakeyaml.Yaml;

/**
 * Checks the Java economy against {@code docs/balance/golden-values.json} (generated by the simulator
 * from docs/balance/model.md), using the real {@code buildings.yml} / {@code upgrades.yml} from the jar's
 * resources. Skipped while any of those files is missing.
 *
 * <p>Costs must match exactly; doubles within 1e-9 relative. Max counts are checked through the
 * {@link Economy} methods with a player who has every unlock (baked = max, buildings owned = 1000), so
 * the unlock rules don't hide a cap or a boundary.
 */
class GoldenValuesTest {

    private static final Path GOLDEN = Path.of("docs/balance/golden-values.json");

    private static JsonObject golden() throws IOException {
        Assumptions.assumeTrue(Files.isRegularFile(GOLDEN), "docs/balance/golden-values.json not present yet");
        try (Reader r = Files.newBufferedReader(GOLDEN, StandardCharsets.UTF_8)) {
            return JsonParser.parseReader(r).getAsJsonObject();
        }
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> resourceYaml(String name) throws IOException {
        try (InputStream in = GoldenValuesTest.class.getClassLoader().getResourceAsStream(name)) {
            Assumptions.assumeTrue(in != null, name + " not present yet");
            Object o = new Yaml().load(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            return (Map<String, Object>) o;
        }
    }

    private static Economy economy() throws Exception {
        EconomyConfig config = EconomyConfigParser.parse(resourceYaml("buildings.yml"), resourceYaml("upgrades.yml")).config();
        return new Economy(config, new java.util.Random(1));
    }

    private static void assertClose(double expected, double actual, String what) {
        double tolerance = 1e-9 * Math.max(Math.abs(expected), Math.abs(actual));
        assertEquals(expected, actual, tolerance, what);
    }

    private static Map<String, Integer> levels(JsonObject json) {
        Map<String, Integer> out = new HashMap<>();
        json.entrySet().forEach(en -> out.put(en.getKey(), en.getValue().getAsInt()));
        return out;
    }

    @Test
    void costGrowthAndMaxBulkMatch() throws Exception {
        JsonObject g = golden();
        Economy e = economy();
        assertEquals(g.get("cost-growth").getAsDouble(), e.config().costGrowth());
        assertEquals(g.get("max-bulk").getAsInt(), BulkMath.MAX_BULK);
    }

    @Test
    void clickValuesMatch() throws Exception {
        JsonObject click = golden().getAsJsonObject("click");
        Economy e = economy();
        JsonObject base = click.getAsJsonObject("base-state");
        CookiePouch empty = CookiePouch.fromSnapshot(PouchSnapshot.EMPTY);
        double p = click.get("crit-chance").getAsDouble();
        double m = click.get("crit-multiplier").getAsDouble();
        double power = e.clickPower(empty);
        assertEquals(base.get("click-power").getAsDouble(), power, "base click power");
        assertClose(base.get("crit-click").getAsDouble(), power * m, "crit click at base");
        assertClose(click.get("expected-factor").getAsDouble(), 1 + p * (m - 1), "expected factor");
        assertClose(base.get("expected-click").getAsDouble(), power * (1 + p * (m - 1)), "expected click at base");
    }

    @Test
    void buildingCostsAndBulkBatchesMatchExactly() throws Exception {
        JsonObject costs = golden().getAsJsonObject("costs");
        Economy e = economy();
        assertFalse(costs.isEmpty());
        assertEquals(costs.keySet(), e.config().buildings().keySet(), "building IDs in golden values vs buildings.yml");
        for (String id : costs.keySet()) {
            JsonObject spec = costs.getAsJsonObject(id);
            JsonArray single = spec.getAsJsonArray("single");
            assertEquals(101, single.size());
            for (int n = 0; n < single.size(); n++) {
                assertEquals(single.get(n).getAsDouble(), e.bulkCost(id, n, 1), id + " single cost at owned=" + n);
            }
            for (Map.Entry<String, JsonElement> bulk : spec.getAsJsonObject("buy-10-from").entrySet()) {
                int from = Integer.parseInt(bulk.getKey());
                assertEquals(bulk.getValue().getAsDouble(), e.bulkCost(id, from, 10), id + " buy-10 from " + from);
            }
            for (JsonElement el : spec.getAsJsonArray("bulk")) {
                JsonObject b = el.getAsJsonObject();
                assertEquals(b.get("cost").getAsDouble(), e.bulkCost(id, b.get("owned").getAsInt(), b.get("count").getAsInt()),
                        id + " bulk " + b);
            }
        }
    }

    @Test
    void upgradeDefinitionsAndLevelCostsMatch() throws Exception {
        JsonObject ups = golden().getAsJsonObject("upgrades");
        Economy e = economy();
        assertEquals(ups.keySet(), e.config().upgrades().keySet(), "upgrade IDs in golden values vs upgrades.yml");
        for (String id : ups.keySet()) {
            JsonObject spec = ups.getAsJsonObject(id);
            UpgradeDef u = e.config().upgrades().get(id);
            assertEquals(spec.get("repeatable").getAsBoolean(), u.repeatable(), id + " repeatable");
            assertEquals(spec.get("cost").getAsDouble(), u.cost(), id + " cost");
            assertEquals(spec.get("type").getAsString(), u.type().configName(), id + " type");
            assertEquals(spec.get("value").getAsDouble(), u.value(), id + " value");
            if (!u.repeatable()) {
                assertEquals(u.cost(), e.upgradeBulkCost(id, 0, 1), id + " one-time cost");
                assertEquals(Double.POSITIVE_INFINITY, e.upgradeBulkCost(id, 1, 1), id + " nothing left to buy");
                continue;
            }
            assertEquals(spec.get("cost-growth").getAsDouble(), u.costGrowth(), id + " cost-growth");
            assertEquals(spec.get("max-level").getAsInt(), u.maxLevel(), id + " max-level");
            JsonArray single = spec.getAsJsonArray("single");
            assertEquals(u.maxLevel(), single.size(), id + " one single cost per level below max-level");
            for (int level = 0; level < single.size(); level++) {
                assertEquals(single.get(level).getAsDouble(), e.upgradeBulkCost(id, level, 1), id + " single at level " + level);
            }
            for (JsonElement el : spec.getAsJsonArray("bulk")) {
                JsonObject b = el.getAsJsonObject();
                assertEquals(b.get("cost").getAsDouble(),
                        e.upgradeBulkCost(id, b.get("level").getAsInt(), b.get("count").getAsInt()), id + " bulk " + b);
            }
        }
    }

    @Test
    void maxAffordableMatchesEveryRecordedCase() throws Exception {
        JsonArray cases = golden().getAsJsonArray("max-affordable");
        Economy e = economy();
        assertTrue(cases.size() > 150, "expected the full case list, got " + cases.size());
        for (JsonElement el : cases) {
            JsonObject c = el.getAsJsonObject();
            String kind = c.get("kind").getAsString();
            String id = c.get("id").getAsString();
            int owned = c.get("owned").getAsInt();
            double pouch = c.get("pouch").getAsDouble();
            String label = kind + " " + id + " owned=" + owned + " pouch=" + pouch + " (" + c.get("case").getAsString() + ")";

            // every unlock met: baked is effectively infinite, every building has 1000 owned
            Map<String, Integer> buildings = new HashMap<>();
            e.config().buildings().keySet().forEach(b -> buildings.put(b, 1000));
            Map<String, Integer> levels = new HashMap<>();
            if (kind.equals("building")) {
                buildings.put(id, owned);
            } else if (owned > 0) {
                levels.put(id, owned);
            }
            CookiePouch p = CookiePouch.fromSnapshot(new PouchSnapshot(pouch, Double.MAX_VALUE, buildings, levels));
            int got = kind.equals("building") ? e.maxAffordableBuildings(p, id) : e.maxAffordableUpgrade(p, id);
            assertEquals(c.get("max").getAsInt(), got, label);
        }
    }

    @Test
    void cpsAndClickPowerMatchForRecordedStates() throws Exception {
        JsonArray states = golden().getAsJsonArray("states");
        JsonObject click = golden().getAsJsonObject("click");
        Economy e = economy();
        double crit = click.get("crit-multiplier").getAsDouble();
        double critChance = click.get("crit-chance").getAsDouble();
        assertTrue(states.size() > 0);
        for (JsonElement el : states) {
            JsonObject s = el.getAsJsonObject();
            Map<String, Integer> owned = levels(s.getAsJsonObject("owned"));
            Map<String, Integer> upgradeLevels = levels(s.getAsJsonObject("upgrades"));
            CookiePouch p = CookiePouch.fromSnapshot(new PouchSnapshot(0, 0, owned, upgradeLevels));
            String label = s.get("profile").getAsString() + "@" + s.get("time").getAsInt() + "s";
            assertClose(s.get("total-cps").getAsDouble(), e.totalCps(p), "total-cps " + label);
            double power = e.clickPower(p);
            assertClose(s.get("click-power").getAsDouble(), power, "click-power " + label);
            assertClose(s.get("normal-click").getAsDouble(), power, "normal-click " + label);
            assertClose(s.get("crit-click").getAsDouble(), power * crit, "crit-click " + label);
            assertClose(s.get("expected-click").getAsDouble(), power * (1 + critChance * (crit - 1)),
                    "expected-click " + label);
        }
    }
}
